
extension DamageEffect {
    /// A single burn tick (fire, lava, etc.).
    public static let burning = create("minecraft.burning")

    /// Drowning.
    public static let drowning = create("minecraft.drowning")

    /// A single freeze tick (powder snow).
    public static let freezing = create("minecraft.freezing")

    /// The default damage effect.
    public static let hurt = create("minecraft.hurt")

    /// Poked by something (a berry bush).
    public static let poking = create("minecraft.poking")

    /// Thorns.
    public static let thorns = create("minecraft.thorns")
}